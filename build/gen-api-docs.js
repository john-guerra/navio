/**
 * Generate docs/ai/API.md from src/params.js.
 *
 * Written rather than hand-maintained for the reason every hand-maintained API
 * doc eventually is: it stops being true. `snapshot()` was documented in
 * CLAUDE.md and in NavioWidget.js and has never existed on the instance.
 *
 * Run by `npm run docs:api`, and checked by test/unit/api-docs-current.test.js,
 * which regenerates and compares. A stale file fails `npm run check`, so the
 * doc cannot fall behind the table it comes from.
 */
import { PARAMS, METHODS } from "../src/params.js";

const esc = (s) => String(s).replace(/\|/g, "\\|");

const defaultOf = (p) =>
  "default" in p
    ? "`" + JSON.stringify(p.default) + "`"
    : "`" + p.defaultText + "`";

export function renderApiDocs() {
  const lines = [];
  lines.push(
    "<!-- Generated by build/gen-api-docs.js. Do not edit by hand. -->"
  );
  lines.push("<!-- Run `npm run docs:api` after changing src/params.js. -->");
  lines.push("");
  lines.push("# Navio API");
  lines.push("");
  lines.push(
    "Every option and method this build exposes, generated from `src/params.js`."
  );
  lines.push(
    "The same table drives the settings panel and `navio.describe()`, so all three agree by construction."
  );
  lines.push("");
  lines.push("```js");
  lines.push('import navio from "navio";           // UMD global: `navio`');
  lines.push("");
  lines.push("const nv = navio(d3.select(el), { height: 400 });");
  lines.push(
    'nv.id("id");                          // a real key, not the row index'
  );
  lines.push("nv.data(rows);");
  lines.push("nv.addAllAttribs();                   // one column per field");
  lines.push("```");
  lines.push("");
  lines.push(
    "d3 and popper.js are **external** - Navio reads them off the host page rather than bundling them. d3 v7 or later."
  );
  lines.push("");

  lines.push("## Options");
  lines.push("");
  lines.push(
    "Pass any of these in the options object, or set them on the instance. A few are read only once (see the notes); `nv.setOptions({...})` applies a batch in an order that works."
  );
  lines.push("");

  const sections = [];
  for (const p of PARAMS)
    if (!sections.includes(p.section)) sections.push(p.section);

  for (const section of sections) {
    lines.push(`### ${section}`);
    lines.push("");
    lines.push("| Option | Type | Default | What it does |");
    lines.push("| --- | --- | --- | --- |");
    for (const p of PARAMS.filter((x) => x.section === section)) {
      const type = p.values
        ? p.values.map((v) => `\`${v}\``).join(" \\| ")
        : p.type;
      lines.push(
        `| \`${p.key}\` | ${type} | ${defaultOf(p)} | ${esc(p.hint)} |`
      );
    }
    lines.push("");
  }

  lines.push("## Methods");
  lines.push("");
  lines.push("| Method | What it is for |");
  lines.push("| --- | --- |");
  for (const m of METHODS)
    lines.push(`| \`${esc(m.signature)}\` | ${esc(m.summary)} |`);
  lines.push("");

  lines.push("## Things that are not obvious");
  lines.push("");
  lines.push(
    "- **Navio never writes to your rows.** Selection and positions live in side tables. Use `nv.isSelected(row)` and `nv.getRowsAtLevel(level)` rather than looking for properties on a row."
  );
  lines.push(
    "- **`height` is the RECORD extent, not the widget's total size.** The header band is added on top of it, so the data area is `height` however long the attribute names are."
  );
  lines.push(
    "- **Filters are evaluated once, when created** - they are not live predicates re-run on redraw, and re-sorting a level deliberately cannot change the selection. See `docs/ai/FILTERING-MODEL.md` before doing anything with filtering."
  );
  lines.push(
    "- **`getFilters()`/`setFilters()` carry the drill-down chain; `NavioWidget.value` carries the selected ROWS.** Bind Navio-to-Navio on the chain, Navio-to-anything-else on the value."
  );
  lines.push(
    "- **Settings persist per container `id`.** With no `id` and no `settingsKey`, nothing is stored - a construction-order key was tried and swapped two widgets' settings whenever they were built in a different order."
  );
  lines.push("");

  return lines.join("\n");
}
